/**
 * 演示账号「填入」提示（第 391 轮）
 *
 * ═══════════════════════════════════════════════════════════════════════
 *  它解决的是「登录页是陌生人看到的第一屏」这件事
 * ═══════════════════════════════════════════════════════════════════════
 * 演示账号的 email 与口令要写在简历/面试材料里。而面试官的第一动作是
 * **手打**一串他并不熟悉的邮箱和口令 —— 打错一次是 401，打错五次是
 * 15 分钟锁定（`login_max_failures=5` / `login_lockout_minutes=15`，
 * 且判定顺序是「先看锁没锁，再看密码对不对」⇒ 锁住期间密码正确也进不去）。
 *
 * ⇒ 这里只做**预填**：点一下把两个输入框填满，用户仍然点**真正的登录按钮**。
 *
 * ═══════════════════════════════════════════════════════════════════════
 *  ★★ 为什么不是「一键体验」那种伪登录
 * ═══════════════════════════════════════════════════════════════════════
 * `Login.vue::handleDemoLogin` 是往 localStorage 塞 `demo-token` 哨兵，
 * **不发登录请求**。后端 `DEMO_MODE=false`（线上现状 + 生产护栏强制）时
 * 它换来的是一整屏 401。把那条修成"能用"，等于让后端承认一个写在前端源码里的
 * 字符串 ⇒ 那是给鉴权开后门，不是体验优化。
 *
 * 本文件走的是**真凭据**：填的是 email + 口令，提交给 `/auth/login`，
 * 服务端照常校验、照常发 token。它没有绕过任何一层。
 *
 * ═══════════════════════════════════════════════════════════════════════
 *  ★★★ 两个必须知道的后果（写在这里，免得日后被当成 bug 排查）
 * ═══════════════════════════════════════════════════════════════════════
 * ① 这两个值会被**编译进前端产物**，等于对任何打开页面的人公开。
 *    这在面试场景下是**有意的**（凭据本来就在简历上），但它意味着：
 *    这个账号**不能**同时是任何真实用户的账号。服务端已按身份加了写保护
 *    （禁改密 / 禁删店，见 `core/auth/demo_identity.py::is_demo_account`）。
 *
 * ② **轮换口令 = 必须重建产物并重新部署。**
 *    改了库里的口令而没重建，旧产物会把**旧口令**填进输入框 ⇒
 *    面试官点一下、点登录、看到「邮箱或密码错误」⇒ 比不填更糟。
 *    ⇒ 门禁 `scripts/check-prod-demo-flag.cjs` 的 H1~H3 钉住了形态，
 *      但「值是否最新」只能靠流程：**换口令那一批必须和重建上线同批**。
 *
 * 留空（默认）= 登录页不出现这个入口。这是刻意的 fail-closed：
 * 没配就没有入口，而不是显示一个点下去会填错东西的按钮。
 */

const EMAIL = String(import.meta.env.VITE_DEMO_HINT_EMAIL || '').trim()
const PASSWORD = String(import.meta.env.VITE_DEMO_HINT_PASSWORD || '').trim()

export const DEMO_HINT = {
  email: EMAIL,
  password: PASSWORD,
  /**
   * 只有两个都配了才显示入口。
   * ★ 半配（只填 email）不显示：点下去密码框仍然空着，等于把
   *   "我准备好了"和"还差一步"画成同一个样子。
   */
  ready: Boolean(EMAIL && PASSWORD),
} as const
