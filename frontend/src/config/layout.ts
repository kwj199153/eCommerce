/**
 * 视口断点规格 · 唯一真源（第 375 轮）
 * ================================
 *
 * ★★★ 与 `PANEL_W` 的分工（别混，这是本文件第二张「表」）
 * ---------------------------------------------------------------------------
 *   · `PANEL_W`     = **布局槽位**宽度 —— 三栏各占多宽。容器怎么变它都不变。
 *   · `VIEWPORT_BP` = **视口**断点 —— 屏幕够不够摆下那三栏。它决定的是
 *                     「**换一种布局形态**」（三栏 ↔ 单栏 + 浮层），
 *                     而不是把某个槽位改窄。
 *   ⇒ 一个治"这一栏占多宽"，一个治"要不要换个排法"。
 *     ⚠️ **把栏宽改小治不了这个问题**：第 375 轮真机实测（七档视口）——
 *        360 / 390 / 430 / 768 四个视口下**中栏全是 0px**、横向溢出最高 428px，
 *        而被挤到 0 的恰恰是唯一不可或缺的中栏（对话主区）。
 *        ⇒ 只能换形态。
 *
 * ★★★ 阈值为什么是 1100（别再重算一遍）
 * ---------------------------------------------------------------------------
 *   · 硬下限 = `sidebar 260 + panelWide 528` = **788**。视口正好 788 时中栏 = 0px，
 *     也就是**已经坏透了**的点 ⇒ **那不是"该切单栏"的点，是"早就该切"的点**。
 *     切形态必须在**坏之前**发生，所以阈值要往上留余量。
 *   · 上限锚点 = **iPad 横屏 1024**（实测中栏仅 236px，勉强但很难用；
 *     而 iPad 竖屏 768 中栏已是 0）⇒ 阈值必须 **> 1024**。
 *   · 下限锚点 = 不让 **1280 笔记本**误入单栏（实测中栏 492px，三栏成立）。
 *   ⇒ 1100 落在两者之间：**≤1100 单栏，≥1280 三栏**。
 *     ⚠️ 1101~1279 这一带（如 1152 老笔记本）仍三栏、中栏偏窄但可用 ——
 *        **"偏窄"与"归零"是两件事**，别为了前者把阈值继续抬高。
 *
 * ★ 与 eEducation 同值（1100）是**刻意**的：两仓槽位宽度同源（260 / 528），
 *   硬下限都是 788，锚点也一样 ⇒ 阈值没有理由不同；同值还便于两仓互相复核。
 *
 * ★★★ 它怎么被消费（唯一一处计算 ⇒ 再 provide 下发）
 *   `Workspace.vue`：`matchMedia(NARROW_MEDIA_QUERY)` → `isNarrow` → `provide('isNarrow')`。
 *   ★★ 为什么用 JS `matchMedia` 而不是纯 CSS `@media`：窄屏不只是"CSS 换个排法"，
 *      还**改 JS 行为**（进窄屏时默认收起左右栏、导航后自动收左栏）。
 *      `@media` 只能改样式、JS 读不到 ⇒ 会出现「CSS 已是单栏、JS 还按三栏算」的
 *      半截状态（eEducation 第 450 轮踩过，本仓照此规避）。
 *   ★★ 为什么数字放这里、并导出 `NARROW_MEDIA_QUERY`：数字一旦有第二处就说不清
 *      真源；而这一个属**静默错**（CSS 与 JS 各用一个阈值时，中间那段宽度两边
 *      都不管，且不报错）。
 */
export const VIEWPORT_BP = {
  /** 视口宽度 **≤ 它** ⇒ 切单栏（左/右栏改浮层，主区独占整屏） */
  narrow: 1100,
  /**
   * 视口高度 **≤ 它** ⇒ 侧边栏切「矮视口紧凑档」（菜单行高 34→30、标题 32→28）。
   *
   * ★ 这是**第二个轴**：`narrow` 治「宽度摆不下三栏」，它治「高度摆不下侧栏内容」。
   *   两件事互不相干 —— 1280×720 的笔记本宽度远超 1100，却同样放不下 805px 的侧栏。
   *
   * ★ 为什么真源放在 TS 而不是只写 CSS：CSS 媒体查询**读不了 TS 常量**
   *   （`@media (max-height: var(--x))` 不合法），所以这个数字在
   *   `styles/sidebar-nav.css` 与 `components/Sidebar/AccountMenu.vue` 里各硬编码一份。
   *   它是**被门禁消费**的真源：`scripts/check-sidebar-layout.cjs` 的 S13a/S13d
   *   逐字比对这三处，任何一处漂移就红。
   *
   * ★ 取 860 的依据（CDP 实测，见 `.workbuddy/probes/cdp-sidebar-fit.mjs`）：
   *   侧栏内容总高 **805px**（logo 64 + 数字员工 285 + 资料库/能力 395 + 账户 61），
   *   与视口宽度无关。860 = 805 + 55 余量：竖屏 iPad（1024）/ Air（1112）
   *   不触发，横屏 iPad（768）/ 720 笔记本 / 手机（844，地址栏还要再吃几十像素）触发。
   */
  compactMaxHeight: 860,
} as const

/**
 * 窄屏判据串 —— `isNarrow` 的**唯一**来源。
 * 消费方一律 `matchMedia(NARROW_MEDIA_QUERY)`，**不许自己拼字符串**。
 */
export const NARROW_MEDIA_QUERY = `(max-width: ${VIEWPORT_BP.narrow}px)`

