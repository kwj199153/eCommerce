"""时间 → JSON 的**统一序列化口径**（唯一真源）。

================================================================================
★ 为什么必须有这个模块（不是"为了整齐"）
================================================================================
本仓的时间列一律是 `DateTime`（**naive，无时区**），由 `datetime.utcnow()`
或数据库 `now()` 写入 ⇒ **库里存的是 UTC 的墙上时间**。

但 `dt.isoformat()` 对 naive 值输出的是 `"2026-09-25T12:00:00"` —— **不带偏移**。
这条字符串对消费端是**有歧义的**：

    ECMA-262 规定：`new Date("2026-09-25T12:00:00")`（date-time 形式、无偏移）
    按**本地时区**解析。

于是 UTC+8 的浏览器把这个时刻读成 `04:00 UTC` —— 与真实值**差 8 小时**。

==============================================================================
★ 危害不是"显示差一点"，而是"只有一部分地方错"
==============================================================================
  · **倒计时**（`expires_at`，TTL 30 分钟）⇒ 一打开就显示"已过期"；
  · **周期起止日期**在午夜附近显示成前一天；
  · 而**金额、状态、账单号全都正确** —— 于是它看起来像"某处随机的 UI bug"，
    而不是"一个系统性的序列化口径问题"。这类缺陷的定位成本极高。

==============================================================================
★ 为什么不各自在模块里 `+ "Z"`
==============================================================================
口径**只有一处**才对。散落的拼接每次都要重新判断"我这个值到底是
naive-UTC 还是 naive-本地"，而**判断错的那一份不会报错**，只会静默偏 8 小时。
本仓第 240 轮之前 `modules/billing/` 里就是 5 个这样的散点。

⇒ 判据：**凡是要把时间放进 JSON 响应，一律走这里**，不得裸调 `.isoformat()`。

★ 已带时区的输入会被归一化到 UTC 后输出（`astimezone`），因此调用方
  既不必先判断、也不怕重复加 `Z` —— 幂等。
"""

from __future__ import annotations

from datetime import datetime, timezone
from typing import Optional

__all__ = ["utc_iso"]


def utc_iso(value: Optional[datetime]) -> Optional[str]:
    """naive-UTC（或已带时区）的时间 → 带偏移的 RFC3339 字符串。

    - `None` 原样透传（JSON 里是 `null`，前端要能吃到这个语义）；
    - naive 值**按 UTC 解释**（本仓的既定约定，见模块 docstring）；
    - aware 值先 `astimezone(utc)` 再输出，保证同一时刻只有一种字符串形态
      （否则 `+08:00` 与 `+00:00` 两种写法会同时出现在接口里，
      给"按字符串比对时间"的测试和缓存键埋雷）。

    >>> utc_iso(datetime(2026, 9, 25, 12, 0))
    '2026-09-25T12:00:00+00:00'
    >>> utc_iso(None) is None
    True
    """
    if value is None:
        return None
    if value.tzinfo is None:
        value = value.replace(tzinfo=timezone.utc)
    else:
        value = value.astimezone(timezone.utc)
    return value.isoformat()
