"""前置条件门禁：点名的技能需要「作用对象」而本次没给 ⇒ **拒答，不进 LLM**（第 251 轮）。

==============================================================================
★ 它挡的是哪一个洞（第 250 轮老板实测，已复现）
==============================================================================
选品分析师里**没有**载入选品，点「上架建议」卡片 ⇒ 系统答
「好的，我们已经确定了评估对象：<某个商品>」并按技能格式给出完整上架建议。
那个商品是**上一轮**对话里出现过的，用户这次从没选过。

机制层的取证结论：点名技能时走 LLM 工具环路、**带全量会话历史**，
而技能正文的「适用条件」首句就是「选品**已判定可做**…」——
技能**假定**对象已存在，却没有任何地方校验过这件事。
于是模型从历史里「续」上了上一轮的对象，用「我们已经确定了」这种
**看起来权威**的措辞交付。它的输出格式完美、商品名正确，
唯一错的是「这个对象用户没选过」，而界面、日志、测试全绿。

==============================================================================
★★ 为什么是 fail-closed、而不是"在 prompt 里叮嘱模型"
==============================================================================
本项目反复踩过的形态就是「声明承诺型假门禁」：写了词、从不生效。
实测也证明模型**不可靠**：同一个会话里，第一次「未载入选品」它正确拒答了，
第二次（历史里已有上一次的结论）它就直接照答 —— 说明守不守规矩取决于
**上下文里有什么**，而不是取决于它有没有被叮嘱。

所以这一条必须是**代码**：前置缺失 ⇒ 连模型都不叫。
`is_context_target_missing()` 的判定真源在机制层（唯一实现），
本模块只负责「哪些技能需要对象」这件**业务知识**与那句文案。

★ `is_context_target_missing()` 对「本客户端未提供该字段」也返回「缺失」——
  那是**故意的安全失败方向**（拿不到权威信息就不能假定有对象）。
  代价是要求调用方先把对象带上，可恢复；反过来判成"有"就是把本洞放回来。

==============================================================================
★ 维护判据：这份名单不许漂移
==============================================================================
`TARGET_REQUIRED_SKILLS` 是**业务知识**（哪条技能必须有个对象才能开工），
它必须与技能仓库里那批候选类技能**逐字相等**。
漂移的两个方向都由门禁兜住（`tests/test_context_target_gate.py`）：

  · 名单里写了个不存在的技能 ⇒ 名字先被否（多半是改名的残留）；
  · 技能仓库里新增了一条候选类技能却忘了登记 ⇒
    门禁按**可推导的规则**（本 Agent 启用中的 `candidate-` 前缀技能）
    现算一份期望值比对 ——
    ★ 生产代码里用显式名单（可 grep、可读），
      推导规则**只写在门禁里**：约定当判据是脆的，当**检查**是硬的。

★★ 「谁参与作用对象机制」≠「谁有拒答门禁」（第 257 轮，两件事别混）
------------------------------------------------------------------------------
第 257 轮把该机制从选品一条链路扩到三条（+ Listing 优化师 / AIGC 媒体生成器），
第 298 轮再补第四条（+ 客服 / 差评应对）——
每条链路的端点都会 `bind_context_target(...)`、都会往 system prompt 注入对象段。
但**拒答门禁只留在选品**，本文件与 `TARGET_REQUIRED_SKILLS` 一个字都没改。

理由：本门禁的成立前提是「该技能**逐字假定**对象已存在」（见上面第 11 行那段
技能正文的引用），缺了就只能从历史里续。而 Listing / AIGC / 客服的技能里有相当
一部分（关键词挖掘、类目分析、风格化素材、FAQ 检索）是按类目 / 风格作答的，
**不需要具体对象** ——
给它挂 fail-closed 等于把一次正常提问变成一句拒答，是**误伤**。
⇒ 这三家是「**只注入、不拒答**」：有对象就用上，没有就不注入，模型照常回答。

★ 将来若要给某一家也加拒答，正确的落点不是把它的技能名塞进这份名单
  （这份名单的语义是"候选类技能"），而是在它自己的模块里另开一份业务知识 +
  复用机制层的 `is_context_target_missing()`（判定真源只有一处）。
"""

from __future__ import annotations

from typing import Optional

from ai_infra.context_target import is_context_target_missing
from ai_infra.skills import current_requested_skill, is_skill_requested

#: 必须先选定「作用对象」才能开工的技能（`skills.name`）。
#:
#: ★ 为什么是这五条：它们回答的都是「**这个品**值不值得做 / 怎么上 / 有什么坑」——
#:   没有对象时，任何结论都无处落脚。其余技能（技能目录里的目录类、门槛类）
#:   是按类目或全市场作答的，不需要具体对象，因此**不拦**（拦了是误伤）。
TARGET_REQUIRED_SKILLS: frozenset = frozenset(
    {
        "candidate-market-feasibility",
        "candidate-launch-advice",
        "candidate-pain-analysis",
        "candidate-risk-scan",
        "candidate-benchmark-compare",
    }
)

#: 前置缺失时的**唯一**文案（唯一实现）。
#:
#: ★ 为什么必须由代码下发、不能让模型"自己说"：模型能看见的只有用户消息里
#:   那句人话，而实测它正是**越过了那句话**去用历史里的对象。
#:   代码下发 ⇒ 这一轮**根本没有模型参与**，也就没有可被历史带偏的机会。
#: ★ 为什么不说"我无法完成"这类含糊话：用户需要知道**下一步做什么**
#:   （点哪个按钮），以及**为什么不能替他挑一个**（挑一个的结论会打在别的品上）。
#:   含糊的拒答在界面上与故障同形，用户只能反复重试。
NEED_TARGET_REPLY = (
    "这次点名的技能需要先选定评估对象：请点顶部的 **【载入选品】** 选定一个候选后再试。\n\n"
    "我没有替你挑一个顶上 —— 那样给出的会是「针对**别的**品」的结论，"
    "看起来完整，其实是错的。"
)


def target_required_skill() -> Optional[str]:
    """本次点名的技能若**需要**作用对象则返回技能名，否则 `None`。

    ★ 没点名（`None`）、点名了但不在名单里 —— 都返回 `None`：
      本门禁只处理「点名 + 需要对象」这一种组合，别的组合一律放行
      （关键词短路、普通提问、目录类技能的行为一个字都不变）。

    ★ 「有没有点名」这个**布尔判定**走 `is_skill_requested()`（全仓唯一实现）；
      本函数多读一次 `current_requested_skill()` 是为了拿**名字去查表** ——
      查「这条技能要不要对象」不是重做那个判定。
      （`tests/test_skill_shortcut_compat.py` 把本文件登记在
      `RAW_JUDGMENT_ALLOWED` 里，注释同源。）
    """
    if not is_skill_requested():
        return None
    name = current_requested_skill()
    return name if name in TARGET_REQUIRED_SKILLS else None


def context_target_rejection() -> Optional[str]:
    """该拒答就返回唯一文案，否则 `None`。

    调用点：`ProductResearchService.chat` / `stream_chat` 的**第一行**
    （在 Agent 之前），两条路径必须是同一个判定 ——
    「流式与非流式只是输出形式，不是另一套智能」是本仓既有判据。
    """
    if target_required_skill() is None:
        return None
    if not is_context_target_missing():
        return None
    return NEED_TARGET_REPLY


__all__ = [
    "TARGET_REQUIRED_SKILLS",
    "NEED_TARGET_REPLY",
    "target_required_skill",
    "context_target_rejection",
]
