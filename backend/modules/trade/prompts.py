"""交易履约域 提示词（**业务资产**）。

★ 为什么正文必须住这里而不是住在 `risk_scan.py`
----------------------------------------------
`tests/test_prompt_spec.py` 有一条门禁：**模块级、名字含 PROMPT 的字符串正文**
（长度 ≥200）不得出现在 `prompts.py` 之外。理由不是洁癖 ——
提示词正文散落在判定逻辑里，就**无法对账、无法覆写、无法算指纹**：
改进提示词时改的是哪一份、线上跑的是哪一份，谁都说不清。

★ 本模块**不注册**到 `ai_infra.llm` 的模板表：
  `risk_scan.scan_llm` 走的是 `structured_chat(system_prompt=...)`（要求严格 JSON），
  与 `register_prompt_template` 那套 `{var}` 渲染范式不是同一条通道；
  硬套注册表会造出「注册了但没人查」的死登记。
"""

#: 买家评论风险话术判定（r1~r5）的语义通道系统提示词。
#: ★ 与 `scripts/data/r299_risk_eval_set.json` 的评测口径同源：
#:   正类 ⟺ 命中 r1~r4；r5 与「无风险」同为负类。
#:
#: ★★ 语域（第 302 轮）：本套判据的输入是**买家已公开发布的商品评价**，
#:   不是买家私信 / 客服会话。r1 因此定义为「**加码**要挟」—— 这条差评本身
#:   已经公开、**不是筹码**，算筹码的只能是「尚未发生的升级动作」。
#:   ★ 两套提示词必须同步改：单条版与批量版是同一口径的两处书写，
