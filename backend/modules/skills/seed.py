async def ensure_demo_skills() -> int:
    """给演示账号预置 23 条示例技能，并把该账号名下的技能标成演示技能。

    Returns:
        本次**发生变化的行数**（0 = 库里已是期望状态，稳态启动走这里）。

    ★ 两步的次序有意义：先确保示例技能存在，再统一刷标记 ——
      否则新建的那条要等到**下一次**启动才带上 `is_demo`。

    ★★★ 第 182 轮：本函数现在同时是「新建 23 条」和「**别再改回去**」的守卫。
      演示身份获得了写权限 ⇒ 老板会真的去改这些技能。
      因此「已有则不覆盖」不是谨慎，而是「演示模式里改的东西重启后还在」
      这个体验的全部依据。想恢复出厂：删掉那条，下次启动按规格表重建。
    """
    account = await demo_account_row()
    if account is None:
        # 演示账号不存在 ⇒ 不动任何标记（fail-closed：宁可演示模式是空的，
        # 也不能因为"找不到账号"就把某条真实技能标成演示技能放出去）。
        return 0

    async with async_session_factory() as session:
        changed = 0

        # ---- ⓪ 先清理已退役的演示技能（幂等：删掉即不再出现）----
        #   ★ 次序在 ① 之前：先腾掉不该在的、再补该在的，否则「退役一条 +
        #     新增一条」时会有一段"两条都在"的中间态被用户看到。
        #   ★ 只删**演示账号名下**的那一条 ⇒ 别的账号的同名技能不受影响。
        #   ★ 它的版本历史由 DB 层 `ondelete='CASCADE'` 一并删除（见 db_model）。
        for retired_name, why in RETIRED_DEMO_SKILLS.items():
            dead = (
                await session.execute(
                    select(SkillRecord).where(
                        SkillRecord.name == retired_name,
                        SkillRecord.account_id == account.id,
                    )
                )
            ).scalar_one_or_none()
            if dead is None:
                continue
            await session.delete(dead)
            changed += 1
            logger.info("🧹 已移除退役的演示技能 %s（%s）", retired_name, why)

        # ---- ① 确保 23 条示例技能存在（幂等：已有则**不覆盖**）----
        for spec in DEMO_SKILLS:
            existing = (
                await session.execute(
                    select(SkillRecord).where(SkillRecord.name == spec["name"])
                )
            ).scalar_one_or_none()
            if existing is not None:
                continue

            # ★ 图标（第 188 轮）：与真实保存走**同一条**路径（留空 ⇒ AI 补）。
            #   刻意**不在规格表里硬编码**：硬编码会让演示数据与真实数据两套口径，
            #   将来换图标机制（比如改成图片）时必漏一处。
            #   ★ 失败返回 None ⇒ 落空串，**绝不阻断 seed** ——
            #     本函数在启动路径上，"图标没生成出来"不该让启动失败。
            icon = await generate_skill_icon(spec["title"], spec["description"]) or ""

            row = SkillRecord(
                id=spec["id"],
                name=spec["name"],
                title=spec["title"],
                icon=icon,
                description=spec["description"],
                content=spec["content"],
                tools=list(spec.get("tools") or []),
                version="1.0.0",
                visibility="account",
                enabled=True,
                enabled_agents=list(spec["agents"]),
                # ★ 卡片开关（第 248 轮）：规格表未标 ⇒ True（= 保持现行为）。
                #   ★ 只在**新建**时落值；**已存在**的行由 `resync_demo_skills()`
                #     显式对账（本函数「已有则不覆盖」，见 docstring 与下方注释）。
                as_shortcut=bool(spec.get("as_shortcut", True)),
                owner_id=account.owner_user_id,
                account_id=account.id,
                is_demo=True,
            )
            session.add(row)
            session.add(
                SkillRevisionRecord(
                    id="rev_" + spec["id"].removeprefix("skill_"),
                    skill_id=row.id,
                    version="1.0.0",
                    content=spec["content"],
                    note="演示示例（预置）",
                    action="create",
                    changed_by=account.owner_user_id,
                )
            )
            changed += 1
            logger.info("✅ 已为演示账号预置示例技能 %s", spec["name"])

        if len(DEMO_SKILLS) != DEMO_SKILL_COUNT:
            # ★ 契约数沿革：10（第 182 轮）→ 23（第 189 轮）→ 22（第 195 轮，
            #   退役 `secretary-handoff-rules`：平台编排内部规则不该是租户可改的）
            #   → 23（第 283 轮，新增 `cs-negative-review-triage`）。
            #   写在这里而不是只在测试里：它是一条**契约**，
            #   而在启动路径上喊出来比在 CI 里红更早、更容易被看见。
            #   （测试仍然有 —— 见 tests/test_skill_gate.py 的覆盖面断言，
            #    它刻意**只钉关系、不钉条数**，所以改条数只需改上面那个常量。）
            logger.warning(
                "演示技能规格表有 %d 条，而本轮契约为 %d 条",
                len(DEMO_SKILLS), DEMO_SKILL_COUNT,
            )

        # ---- ② 双向收敛演示标记（对**该账号名下全部**技能）----
        rows: List[SkillRecord] = (
            await session.execute(
                select(SkillRecord).where(SkillRecord.account_id == account.id)
            )
        ).scalars().all()
        for skill in rows:
            if bool(skill.is_demo) is not True:
                skill.is_demo = True
                changed += 1

        # ---- ③ 其余账号的技能一律降回 False（防止历史残留）----
        others = (
            await session.execute(
                select(SkillRecord).where(
                    SkillRecord.is_demo.is_(True),
                    (SkillRecord.account_id.is_(None))
                    | (SkillRecord.account_id != account.id),
                )
            )
        ).scalars().all()
        for skill in others:
            skill.is_demo = False
            changed += 1

        if changed:
            await session.commit()

    return changed


async def resync_demo_skills(*, dry_run: bool = False) -> List[str]:
    """**显式**对账入口：把规格表的**配置列**同步到已存在的演示技能行上。

    Returns:
        本次被改动的技能 `name` 列表（`dry_run=True` 时是「将要被改的」）。

    同步四列（语义**不完全相同**，逐列说明）：

        `enabled_agents`  以规格表为准（值不同就覆盖）
        `tools`           以规格表为准（值不同就覆盖）
        `as_shortcut`     以规格表为准（值不同就覆盖）—— 第 248 轮
        `icon`            **只补空** —— 已有值绝不覆盖（见下）

    ==========================================================================
    ★★★ 为什么不合并进 `ensure_demo_skills()`
    ==========================================================================
    第 182 轮把「已有则不覆盖」从谨慎升级成了**体验依据** —— 演示身份能改技能，
    所以"重启不覆盖"就是「演示模式里改的东西还在」这条体验的全部依据。

    而 `enabled_agents` 是**用户能在界面上勾的**（「Agent 内勾选启用」正是主链路），
    与 `content` 同属"用户可能改过"的列。若让启动路径每次覆盖它，
    老板在演示里勾掉的 Agent 会在重启后**静默长回来** —— 比不生效更糟
    （他会以为自己改错了，而不是"种子又覆盖了"）。
    ⇒ 启动路径一律不碰；只由本函数**显式**触发（CLI：`--resync`）。

    ==========================================================================
    ★ 只同步「配置列」，绝不碰「内容列」
    ==========================================================================
    同步：`enabled_agents`、`tools`、`as_shortcut`、`icon`（仅空值）
    不动：`content` / `title` / `description` / `version` / `visibility`
          —— 改这些等于抹掉老板的编辑，且会**绕过版本快照**机制
          （正文应该走 `service.update_skill` 才会落 revision）。

    ==========================================================================
    ★★ 为什么 `icon` 是「只补空」而不是「以规格表为准」
    ==========================================================================
    另两列的权威在**规格表**（`DEMO_SKILLS` 写了该挂哪个 Agent）。
    图标的权威**不在规格表** —— 它是每个技能现场生成的，而且需求原文
    明确写了「**允许手工改**」。所以：
      · 空 ⇒ 补（这就是「留空则 AI 补」在**已有行**上的落点）
      · 非空 ⇒ 原样留着（老板改过的图标不能被对账抹掉）
    这也让本函数可以**反复跑**：稳态时返回空列表。

    ★ 用"值不同才写"判定而不是无条件赋值：值相同就不写库，
      于是「稳态调用返回空列表」是一条可复算的读数。

    ★ `dry_run=True` 时**不调用 LLM**（补图标要出网）：干跑只报告
      「这条的图标是空的、真跑时会去补」，不产生任何外部调用与写入。
    """
    account = await demo_account_row()
    if account is None:
        return []

    spec_by_name = {s["name"]: s for s in DEMO_SKILLS}
    changed: List[str] = []

    async with async_session_factory() as session:
        rows = (
            await session.execute(
                select(SkillRecord).where(SkillRecord.account_id == account.id)
            )
        ).scalars().all()

        for row in rows:
            spec = spec_by_name.get(row.name)
            if spec is None:
                # 老板自己新建的技能：不在规格表里 ⇒ **不归本函数管**。
                # （否则"对账"会变成"把用户新增的东西删光/改光"。）
                continue

            touched = False

            want_agents = list(spec["agents"])
            if list(row.enabled_agents or []) != want_agents:
                row.enabled_agents = want_agents
                touched = True

            want_tools = list(spec.get("tools") or [])
            if list(row.tools or []) != want_tools:
                row.tools = want_tools
                touched = True

            # ---- as_shortcut（第 248 轮）：以**规格表**为准（同 enabled_agents / tools）----
            #   ★ 与 `icon` 刻意不同：图标是"只补空"，因为它的权威**不在规格表**
            #     （每条现场生成 + 需求原文允许手工改）；而"这条技能是不是规矩型"
            #     是**只有规格表才知道**的事 ⇒ 权威在规格表，值不同就覆盖。
            #   ★ 与 `enabled_agents` 同族风险、同样处置：它也是用户能在界面上拨的
            #     开关 ⇒ 只在**显式** `--resync` 时覆盖，启动路径一律不碰
            #     （否则老板在演示里拨的开关会在重启后静默弹回来）。
            want_shortcut = bool(spec.get("as_shortcut", True))
            if bool(getattr(row, "as_shortcut", True)) != want_shortcut:
                row.as_shortcut = want_shortcut
                touched = True

            # ---- icon：**只补空** ----
            if not (getattr(row, "icon", "") or "").strip():
                if dry_run:
                    touched = True  # 「真跑时会去补」—— 但不在这里出网
                else:
                    new_icon = await generate_skill_icon(
                        row.title or spec["title"],
                        row.description or spec["description"],
                    )
                    if new_icon:
                        row.icon = new_icon
                        touched = True

            if touched:
                changed.append(row.name)

        if changed and not dry_run:
            await session.commit()

    return changed


